import { launchChrome } from './lib/chrome.mjs';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const s = await launchChrome({ width: 1440, height: 900, logDir: 'C:/Users/Dell/Desktop/kaldanhotel/capture/prototype' });
const ev = async (e) => { const r = await s.cdp.send('Runtime.evaluate', { expression: e, returnByValue: true, awaitPromise: true }); return r.result.value; };
const sw = async (label) => console.log(label, JSON.stringify(await ev(`({ sw: document.documentElement.scrollWidth, iw: innerWidth, sy: Math.round(scrollY), layers: !!document.querySelector('.layers'), drawerInLayers: !!document.querySelector('.layers .drawer') })`)));
await s.goto('http://127.0.0.1:8899/', { waitMs: 3000 });
await sw('load');
for (const id of ['story', 'estate', 'stay', 'experiences', 'dine', 'celebrate', 'praise', 'enquire']) {
  await ev(`document.getElementById('${id}').scrollIntoView({behavior:'instant',block:'start'}); window.scrollBy(0,-70);`);
  await sleep(500);
}
await sw('after chapters');
await ev(`document.getElementById('stay').scrollIntoView({behavior:'instant'}); document.querySelector('[data-room="luxury-villa"]').click()`);
await sleep(600); await sw('room');
await ev(`document.getElementById('experiences').scrollIntoView({behavior:'instant'}); document.querySelector('[data-exp="kayak"]').click()`);
await sleep(500); await sw('exp open');
await ev(`document.getElementById('expAddBtn').click(); document.getElementById('expModalClose').click()`);
await sleep(400); await sw('exp closed');
await ev(`document.getElementById('dine').scrollIntoView({behavior:'instant'}); document.querySelector('[data-dine="panch"] .dine-head').click()`);
await sleep(700); await sw('dine');
await ev(`document.getElementById('reserveBtn').click()`);
await sleep(700); await sw('drawer open');
await ev(`document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`);
await sleep(600); await sw('drawer esc');
await ev(`document.getElementById('enquire').scrollIntoView({behavior:'instant'}); document.getElementById('enqName').value='A'; document.getElementById('enqEmail').value='a@b.co'; document.getElementById('enqSubmit').click()`);
await sleep(400); await sw('enquiry');
await ev(`document.getElementById('inspectorToggle').click()`);
await sleep(400); await sw('inspector');
await ev(`document.getElementById('inspectorClose').click(); window.scrollTo(0,0)`);
await sleep(500);
await ev(`document.getElementById('filmBtn').click()`);
await sleep(900); await sw('film open');
await ev(`document.getElementById('filmClose').click()`);
await sleep(400); await sw('film closed');
await ev(`document.getElementById('menuBtn').click()`);
await sleep(900); await sw('menu open');
await ev(`document.getElementById('menuBtn').click()`);
await sleep(600); await sw('menu closed');
await s.close();